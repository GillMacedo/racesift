func TestTruncatedReport(t *testing.T) {
	data, err := os.ReadFile(filepath.Join(logs, "warm.log"))
	if err != nil {
		t.Fatal(err)
	}
	cut := string(data)[:strings.Index(string(data), "Goroutine 7")]
	reports, _, _, err := Parse(strings.NewReader(cut), "cut")
	if err != nil {
		t.Fatal(err)
	}
	if len(reports) != 1 || !reports[0].Truncated || len(reports[0].Accesses) != 2 {
		t.Fatalf("got %+v", reports)
	}
	half := cut[:strings.Index(cut, "Previous ")]
	s := Review(mustParse(t, half))
	if len(s.Races) != 1 || hintIDs(s.Races[0]) != "RS000" {
		t.Errorf("one-sided report: %d races, hints %s", len(s.Races), hintIDs(s.Races[0]))
	}
}

func mustParse(t *testing.T, s string) []*Report {
	t.Helper()
	r, _, _, err := Parse(strings.NewReader(s), "test")
	if err != nil {
		t.Fatal(err)
	}
	return r
}

