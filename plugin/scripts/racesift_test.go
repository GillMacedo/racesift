func TestCompareShop(t *testing.T) {
	c := Compare(review(t, "shop-v1.log"), review(t, "shop-v2.log"))
	if len(c.New) != 1 || len(c.Gone) != 1 || len(c.Still) != 3 {
		t.Fatalf("new %d, gone %d, still %d", len(c.New), len(c.Gone), len(c.Still))
	}
	if sides(c.New[0]) != "reserve_v2.go:11 reserve_v2.go:11" {
		t.Errorf("new = %s", sides(c.New[0]))
	}
	if sides(c.Gone[0]) != "cache.go:18 cache.go:25" {
		t.Errorf("gone = %s", sides(c.Gone[0]))
	}
	var out bytes.Buffer
	base, head := filepath.Join(logs, "shop-v1.log"), filepath.Join(logs, "shop-v2.log")
	if code := run([]string{"compare", base, head}, nil, &out, &out); code != 0 {
		t.Errorf("compare without --fail exit %d", code)
	}
	if code := run([]string{"compare", "--fail", base, head}, nil, &out, &out); code != 1 {
		t.Errorf("compare --fail with a new race exit %d", code)
	}
	if code := run([]string{"compare", "--fail", head, head}, nil, &out, &out); code != 0 {
		t.Errorf("compare --fail with no new race exit %d", code)
	}
}

