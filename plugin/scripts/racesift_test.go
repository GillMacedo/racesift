const logs = "../../examples/logs"

func review(t *testing.T, name string) *Summary {
	t.Helper()
	s, err := load(filepath.Join(logs, name), nil)
	if err != nil {
		t.Fatal(err)
	}
	return s
}

func hintIDs(r *Race) string {
	var ids []string
	for _, h := range r.Hints {
		ids = append(ids, h.ID)
	}
	return strings.Join(ids, ",")
}

func sides(r *Race) string {
	var out []string
	for _, l := range r.Locations {
		out = append(out, filepath.Base(l.File)+":"+strconv.Itoa(l.Line))
	}
	sort.Strings(out)
	return strings.Join(out, " ")
}

type wantRace struct {
	sides string
	tests string
	hints string
}

// The shop logs come from real runs of examples/programs. The same four races
// must come out of the plain, verbose, JSON and GitHub Actions forms.
func TestReviewTop(t *testing.T) {
	log := filepath.Join("..", "..", "examples", "logs", "shop-v1.log")
	var all, out bytes.Buffer
	if code := run([]string{"review", log}, nil, &all, &all); code != 0 {
		t.Fatalf("exit %d: %s", code, all.String())
	}
	if code := run([]string{"review", "--top", "1", "--fail", log}, nil, &out, &out); code != 1 {
		t.Fatalf("--fail must still see every race: exit %d", code)
	}
	text := out.String()
	if !strings.Contains(text, "4 distinct races") || !strings.Contains(text, "RACE 1 ") || strings.Contains(text, "RACE 2 ") || !strings.Contains(text, "3 more races not shown") {
		t.Errorf("got:\n%s", text)
	}
	if !strings.Contains(all.String(), "RACE 4 ") || strings.Contains(all.String(), "not shown") {
		t.Errorf("without --top:\n%s", all.String())
	}
	if code := run([]string{"review", "--top", "-1", log}, nil, &out, &out); code != 2 {
		t.Errorf("negative --top: exit %d", code)
	}
}

func TestShopLogsAllForms(t *testing.T) {
	want := []wantRace{
		{"cache.go:18 cache.go:25", "TestCacheConcurrentRefresh,TestLoadAll,TestCacheWarmAndServe", "RS101"},
		{"batch.go:25 batch.go:25", "TestLoadAll", "RS103,RS105"},
		{"audit.go:14 audit.go:14", "TestReserve", "RS104,RS105"},
		{"<autogenerated>:1 stats.go:15", "TestStats", "RS102,RS108"},
	}
	for _, name := range []string{"shop-v1.log", "shop-v1-verbose.log", "shop-v1.json", "written/github-actions.log"} {
		t.Run(name, func(t *testing.T) {
			s := review(t, name)
			if len(s.Races) != len(want) {
				t.Fatalf("got %d races, want %d", len(s.Races), len(want))
			}
			for i, w := range want {
				r := s.Races[i]
				if got := sides(r); got != w.sides {
					t.Errorf("race %d sides = %q, want %q", i+1, got, w.sides)
				}
				if got := strings.Join(r.Tests, ","); got != w.tests {
					t.Errorf("race %d tests = %q, want %q", i+1, got, w.tests)
				}
				if got := hintIDs(r); got != w.hints {
					t.Errorf("race %d hints = %q, want %q", i+1, got, w.hints)
				}
			}
			if strings.Join(s.Packages, ",") != "example.com/shop/inventory" {
				t.Errorf("packages = %v", s.Packages)
			}
			if s.Truncated != 0 {
				t.Errorf("truncated = %d", s.Truncated)
			}
		})
	}
	if !review(t, "shop-v1.json").JSONInput {
		t.Error("JSON input not detected")
	}
}

